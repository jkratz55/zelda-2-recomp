#!/usr/bin/env python3
"""random_input.py - generate a reproducible "random play" input script.

Starts a new game (title -> name entry -> North Palace) and then mashes
random directions and buttons. Used to exercise as much game code as
possible, both to discover code for the recompiler and as a test input for
tools/verify.sh.

usage: random_input.py SEED FRAMES > tests/random_SEED.txt
"""
import os
import random
import sys

seed, frames = int(sys.argv[1]), int(sys.argv[2])
rng = random.Random(seed)
here = os.path.dirname(os.path.abspath(__file__))
intro = open(os.path.join(here, "..", "tests", "new_game.txt")).read()
print("# random play, seed %d, %d frames (generated by tools/random_input.py)" % (seed, frames))
print("\n".join(l for l in intro.splitlines() if l and not l.startswith("#")))
print("1100 1400 LEFT")  # leave the palace

f = 1400
dirs = ["LEFT", "RIGHT", "UP", "DOWN", "LEFT", "RIGHT"]
while f < frames:
    length = rng.randint(20, 150)
    d = rng.choice(dirs)
    print("%d %d %s" % (f, f + length, d))
    # sprinkle in attacks, jumps, crouches
    t = f
    while t < f + length:
        t += rng.randint(5, 40)
        b = rng.choice(["A", "B", "B", "A+B", "DOWN+B"])
        print("%d %d %s" % (t, t + rng.randint(1, 12), b))
    if rng.random() < 0.08:
        print("%d %d START" % (f + length, f + length + 2))  # pause menu / continue
    if rng.random() < 0.03:
        print("%d %d SELECT" % (f + length, f + length + 2))
    f += length
